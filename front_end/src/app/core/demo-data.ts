const D = (offset: number) => addDays(today(), offset);

/** Raccourci de construction d'une ligne sans remise. */
function line(
  id: string,
  description: string,
  deliverableType: DeliverableType,
  quantity: number,
  unitPrice: number,
  vatRate: number,
): Line {
  return {
    id,
    description,
    deliverableType,
    quantity,
    unitPrice,
    discountType: 'PERCENT',
    discountValue: 0,
    vatRate,
  };
}

